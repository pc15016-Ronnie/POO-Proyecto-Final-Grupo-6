CREATE TABLE usuario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(60)  NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    rol            VARCHAR(20)  NOT NULL,
    activo         BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP(6) NOT NULL DEFAULT now(),
    CONSTRAINT uq_usuario_username UNIQUE (username),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMINISTRADOR', 'ASISTENTE'))
);

-- PERSONA es abstracta: guarda los datos comunes a ADMINISTRADOR y ASISTENTE.
-- tipo_persona es la columna tecnica que usa Hibernate para la herencia JOINED.
CREATE TABLE persona (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_persona        VARCHAR(20)  NOT NULL,
    nombre              VARCHAR(80)  NOT NULL,
    apellido            VARCHAR(80)  NOT NULL,
    email               VARCHAR(120) NOT NULL,
    telefono            VARCHAR(30),
    fecha_creacion      TIMESTAMP(6) NOT NULL DEFAULT now(),
    fecha_actualizacion TIMESTAMP(6),
    usuario_id          BIGINT,
    CONSTRAINT uq_persona_email   UNIQUE (email),
    CONSTRAINT uq_persona_usuario UNIQUE (usuario_id),
    CONSTRAINT ck_persona_tipo    CHECK (tipo_persona IN ('ADMINISTRADOR', 'ASISTENTE')),
    CONSTRAINT fk_persona_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE TABLE administrador (
    id           BIGINT PRIMARY KEY,
    departamento VARCHAR(80),
    CONSTRAINT fk_administrador_persona FOREIGN KEY (id) REFERENCES persona (id) ON DELETE CASCADE
);

CREATE TABLE asistente (
    id BIGINT PRIMARY KEY,
    CONSTRAINT fk_asistente_persona FOREIGN KEY (id) REFERENCES persona (id) ON DELETE CASCADE
);

CREATE TABLE ubicacion (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(100) NOT NULL,
    direccion VARCHAR(200),
    ciudad    VARCHAR(100),
    capacidad INTEGER      NOT NULL,
    latitud   DOUBLE PRECISION,
    longitud  DOUBLE PRECISION,
    CONSTRAINT ck_ubicacion_capacidad CHECK (capacidad > 0)
);

CREATE TABLE evento (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ubicacion_id        BIGINT       NOT NULL,
    nombre              VARCHAR(120) NOT NULL,
    descripcion         VARCHAR(500),
    fecha_inicio        TIMESTAMP(6) NOT NULL,
    fecha_fin           TIMESTAMP(6),
    capacidad_maxima    INTEGER      NOT NULL,
    estado              VARCHAR(20)  NOT NULL,
    fecha_creacion      TIMESTAMP(6) NOT NULL DEFAULT now(),
    fecha_actualizacion TIMESTAMP(6),
    CONSTRAINT fk_evento_ubicacion FOREIGN KEY (ubicacion_id) REFERENCES ubicacion (id),
    CONSTRAINT ck_evento_capacidad CHECK (capacidad_maxima > 0),
    CONSTRAINT ck_evento_estado    CHECK (estado IN ('BORRADOR', 'PUBLICADO', 'CANCELADO', 'FINALIZADO'))
);

CREATE INDEX ix_evento_estado_fecha ON evento (estado, fecha_inicio);
CREATE INDEX ix_evento_ubicacion ON evento (ubicacion_id);

CREATE TABLE registro (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id         BIGINT       NOT NULL,
    asistente_id      BIGINT       NOT NULL,
    estado            VARCHAR(20)  NOT NULL,
    fecha_registro    TIMESTAMP(6) NOT NULL DEFAULT now(),
    fecha_cancelacion TIMESTAMP(6),
    CONSTRAINT fk_registro_evento    FOREIGN KEY (evento_id) REFERENCES evento (id) ON DELETE CASCADE,
    CONSTRAINT fk_registro_asistente FOREIGN KEY (asistente_id) REFERENCES asistente (id) ON DELETE CASCADE,
    CONSTRAINT ck_registro_estado    CHECK (estado IN ('ACTIVO', 'CANCELADO'))
);

-- RN-04: un asistente solo puede tener un registro ACTIVO por evento.
-- Es un indice unico PARCIAL: permite volver a inscribirse despues de cancelar.
CREATE UNIQUE INDEX uq_registro_activo ON registro (evento_id, asistente_id) WHERE estado = 'ACTIVO';
CREATE INDEX ix_registro_evento_estado ON registro (evento_id, estado);
